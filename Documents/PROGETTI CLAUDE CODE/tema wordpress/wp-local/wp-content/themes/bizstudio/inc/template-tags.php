/**
 * Output star rating HTML.
 */
function bizstudio_star_rating( float $rating, int $count = 0 ): string {
	$html = '<div class="biz-rating">';
	for ( $i = 1; $i <= 5; $i++ ) {
		$html .= $i <= round( $rating ) ? bizstudio_icon( 'star' ) : bizstudio_icon( 'star-empty' );
	}
	if ( $count > 0 ) {
		$html .= '<span class="biz-rating__count">(' . $count . ')</span>';
	}
	$html .= '</div>';
	return $html;
}

/**
 * Get sale percentage.
 */
function bizstudio_sale_percentage( $product ): int {
	if ( ! $product->is_on_sale() ) {
		return 0;
	}
	$regular = (float) $product->get_regular_price();
	$sale    = (float) $product->get_sale_price();
	if ( $regular <= 0 ) {
		return 0;
	}
	return round( ( ( $regular - $sale ) / $regular ) * 100 );
}
